export function lessonById(id) {
  return LESSONS.find((lesson) => lesson.id === id) || null;
}

export function succeeds(fen, spec, goal) {
  const chess = new Chess(fen);
  const wasCheck = chess.isCheck();
  let move;
  try {
    move = chess.move({ from: spec.from, to: spec.to, promotion: spec.promotion });
  } catch {
    return false;
  }
  if (!move) return false;
  if (goal.kind === "to") {
    return move.to === goal.to && (!goal.promotion || move.promotion === goal.promotion);
  }
  if (goal.kind === "castle") {
    return goal.side === "k" ? move.isKingsideCastle() : move.isQueensideCastle();
  }
  if (goal.kind === "mate") return chess.isCheckmate();
  if (goal.kind === "escape") return wasCheck && !chess.isCheck();
  if (goal.kind === "capture") return Boolean(move.captured) && move.to === goal.square;
  return false;
}
